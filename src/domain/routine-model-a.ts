export const ROUTINE_DAY_LIST: readonly RoutineDayDefinition[] = DAY_ORDER.map(
  (dayKey) => ROUTINE_DAYS[dayKey],
);

export function getRoutineDay(dayKey: DayKey): RoutineDayDefinition {
  return ROUTINE_DAYS[dayKey];
}

export function findExerciseById(exerciseId: string): ExerciseDefinition | undefined {
  for (const dayKey of DAY_ORDER) {
    const found = ROUTINE_DAYS[dayKey].exercises.find((ex) => ex.id === exerciseId);
    if (found) return found;
  }
  return undefined;
}

export function getAllWeightExercises(): ExerciseDefinition[] {
  const result: ExerciseDefinition[] = [];
  for (const dayKey of DAY_ORDER) {
    result.push(...ROUTINE_DAYS[dayKey].exercises);
  }
  return result;
}

export function scaleInitialWeightForOneRm(
  exercise: ExerciseDefinition,
  baseOneRm: OneRmMap,
): number {
  if (exercise.role === 'backoff' && exercise.pairedTopExerciseId && exercise.backoffRatio) {
    const topExercise = findExerciseById(exercise.pairedTopExerciseId);
    if (topExercise) {
      const scaledTop = scaleInitialWeightForOneRm(topExercise, baseOneRm);
      return roundTo2_5(scaledTop * exercise.backoffRatio);
    }
  }

  if (!exercise.liftKey) {
    return exercise.defaultWeightKg;
  }

  const defaultRm = DEFAULT_USER_PROFILE.baseOneRm[exercise.liftKey];
  const userRm = baseOneRm[exercise.liftKey];

  if (!Number.isFinite(userRm) || userRm <= 0 || defaultRm <= 0) {
    return exercise.defaultWeightKg;
  }

  if (userRm === defaultRm) {
    return exercise.defaultWeightKg;
  }

  return roundTo2_5(exercise.defaultWeightKg * (userRm / defaultRm));
}
